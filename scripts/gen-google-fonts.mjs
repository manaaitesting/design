/**
 * Regenerates `src/lib/google-fonts.ts` from Google's own font metadata.
 *
 *     node scripts/gen-google-fonts.mjs
 *
 * The endpoint below is the one fonts.google.com calls for its own directory,
 * so it needs no API key and carries what a font menu actually has to know:
 * which weights and italics a family ships, which variable axes it exposes, and
 * how popular it is. The output is one compact line per family rather than
 * JSON — 1,900 families of pretty-printed objects is a megabyte of bundle for
 * data that is nine tenths punctuation.
 */
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://fonts.google.com/metadata/fonts';

const CATEGORY = {
  'Sans Serif': 's',
  Serif: 'f',
  Display: 'd',
  Handwriting: 'h',
  Monospace: 'm',
};

/** 100–900 become 1–9, and Recursive's 1000 becomes `a`. */
const digit = (weight) => (weight >= 1000 ? 'a' : String(weight / 100));

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
// the response is XSSI-guarded with a )]}' prefix
const meta = JSON.parse((await response.text()).replace(/^\)\]\}'\s*/, ''));

const lines = meta.familyMetadataList
  // most popular first: a font menu is read from the top, and this is the order
  // Google's own directory defaults to
  .sort((a, b) => a.popularity - b.popularity)
  .map((family) => {
    const styles = Object.keys(family.fonts);
    const roman = styles.filter((s) => !s.endsWith('i')).map((s) => digit(Number(s)));
    const italic = styles.filter((s) => s.endsWith('i')).map((s) => digit(parseInt(s, 10)));
    const axes = (family.axes ?? [])
      // `ital` is the italic list, which is already carried above
      .filter((axis) => axis.tag !== 'ital')
      .map((axis) => `${axis.tag} ${axis.min} ${axis.max} ${axis.defaultValue}`)
      .join(';');
    return [family.family, CATEGORY[family.category] ?? 's', roman.join(''), italic.join(''), axes].join('|');
  });

const axisNames = Object.fromEntries(
  meta.axisRegistry.map((axis) => [axis.tag, axis.displayName]),
);

const file = `/**
 * Every family in the Google Fonts directory.
 *
 * Generated by \`scripts/gen-google-fonts.mjs\` from fonts.google.com's own
 * metadata — do not edit by hand. Each line is
 *
 *     name|category|weights|italic weights|axes
 *
 * with weights written as one digit per hundred (\`4\` is 400, \`a\` is 1000) and
 * each axis as \`tag min max default\`. Families are in popularity order, which
 * is the order the picker's "Popular fonts" filter shows them in.
 */

/** What the variable-axis sliders are labelled, by tag. */
export const AXIS_NAMES: Record<string, string> = ${JSON.stringify(axisNames, null, 2)};

export const GOOGLE_FONT_DATA = \`\\
${lines.join('\n')}\`;
`;

writeFileSync(new URL('../src/lib/google-fonts.ts', import.meta.url), file);
console.log(`wrote ${lines.length} families`);
